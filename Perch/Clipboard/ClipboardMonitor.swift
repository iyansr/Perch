import AppKit
import Foundation

/// Polls the general pasteboard and records new content in `ClipboardStore`.
/// Follows `AppSettings.clipboardEnabled`: false stops the timer.
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    nonisolated static let pollInterval: TimeInterval = 0.5
    nonisolated static let maxFiles = 32
    nonisolated static let maxTextLength = 32_000
    nonisolated static let maxImageBytes = 20 * 1024 * 1024

    /// What one pasteboard change contributes to history.
    nonisolated enum Payload {
        case files([URL])
        case text(String)
        /// Raw image bytes: PNG as-is, anything else (TIFF) gets re-encoded to PNG off the main actor.
        case image(Data, isPNG: Bool)
    }

    private let pasteboard: NSPasteboard
    private let settings: AppSettings
    private let store: ClipboardStore
    private var timer: Timer?
    private var lastChangeCount: Int
    private var isStarted = false

    init(pasteboard: NSPasteboard = .general, settings: AppSettings = .shared, store: ClipboardStore = .shared) {
        self.pasteboard = pasteboard
        self.settings = settings
        self.store = store
        self.lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard !isStarted else { return }
        isStarted = true
        apply()
        observeSetting()
    }

    func stop() {
        isStarted = false
        stopTimer()
    }

    // MARK: Lifecycle

    private func observeSetting() {
        withObservationTracking {
            _ = settings.clipboardEnabled
        } onChange: { [weak self] in
            Task { @MainActor [weak self] in
                guard let self, isStarted else { return }
                apply()
                observeSetting()
            }
        }
    }

    private func apply() {
        if settings.clipboardEnabled { startTimer() } else { stopTimer() }
    }

    private func startTimer() {
        guard timer == nil else { return }
        // Content copied while disabled or stopped is never captured.
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func stopTimer() {
        timer?.invalidate()
        timer = nil
    }

    // MARK: Capture

    /// Reads the pasteboard only when `changeCount` moved.
    func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        capture()
    }

    private func capture() {
        guard Self.shouldCapture(pasteboard), let payload = Self.payload(from: pasteboard) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        switch payload {
        case .files(let urls):
            store.insertFiles(urls, source: source)
        case .text(let text):
            store.insertText(text, source: source)
        case .image(let data, let isPNG):
            Task { @MainActor [weak self] in
                let png = await Task.detached(priority: .utility) { Self.pngData(from: data, isPNG: isPNG) }.value
                guard let self, settings.clipboardEnabled, let png else { return }
                store.insertImage(pngData: png, source: source)
            }
        }
    }

    // MARK: Pure decisions

    nonisolated static let blockedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    /// Password-manager guards first and unconditional, then Perch's own writes.
    nonisolated static func shouldCapture(_ pasteboard: NSPasteboard) -> Bool {
        var types = Set(pasteboard.types ?? [])
        for item in pasteboard.pasteboardItems ?? [] { types.formUnion(item.types) }
        if !types.isDisjoint(with: blockedTypes) { return false }
        return !types.contains(.perchInternal)
    }

    /// Files first (Finder also puts the display name on the string type), then text, then image.
    nonisolated static func payload(from pasteboard: NSPasteboard) -> Payload? {
        let files = capturableFiles(fileURLs(on: pasteboard))
        if !files.isEmpty { return .files(files) }

        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(String(text.prefix(maxTextLength)))
        }

        if let data = pasteboard.data(forType: .png) { return imagePayload(data, isPNG: true) }
        if let data = pasteboard.data(forType: .tiff) { return imagePayload(data, isPNG: false) }
        return nil
    }

    nonisolated private static func imagePayload(_ data: Data, isPNG: Bool) -> Payload? {
        data.count > maxImageBytes ? nil : .image(data, isPNG: isPNG)
    }

    /// Each pasteboard item's own `public.file-url`; a copied http URL is not a file.
    nonisolated static func fileURLs(on pasteboard: NSPasteboard) -> [URL] {
        (pasteboard.pasteboardItems ?? []).compactMap { item -> URL? in
            guard let string = item.string(forType: .fileURL),
                  let url = URL(string: string), url.isFileURL
            else { return nil }
            return (url as NSURL).filePathURL ?? url
        }
    }

    /// Drops volatile locations, then caps the batch at `maxFiles`.
    nonisolated static func capturableFiles(_ urls: [URL]) -> [URL] {
        Array(urls.filter { !isVolatile($0) }.prefix(maxFiles))
    }

    nonisolated static let volatileRoots: [String] = [
        "/tmp",
        "/var/folders",
        FileManager.default.homeDirectoryForCurrentUser.appending(path: "Library/Caches").path,
    ].map { canonicalPath($0) }

    nonisolated static func isVolatile(_ url: URL, roots: [String] = volatileRoots) -> Bool {
        let path = canonicalPath(url)
        return roots.contains { path == $0 || path.hasPrefix($0 + "/") }
    }

    /// Finder reports `/private/tmp/…`, shells report `/tmp/…`. Resolve symlinks and fold `/private` so both compare equal.
    nonisolated static func canonicalPath(_ path: String) -> String {
        canonicalPath(URL(fileURLWithPath: path))
    }

    nonisolated static func canonicalPath(_ url: URL) -> String {
        let resolved = url.resolvingSymlinksInPath().standardizedFileURL.path
        return resolved.hasPrefix("/private/") ? String(resolved.dropFirst("/private".count)) : resolved
    }

    nonisolated static func pngData(from data: Data, isPNG: Bool) -> Data? {
        let png: Data?
        if isPNG {
            png = data
        } else {
            png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
        }
        guard let png, png.count <= maxImageBytes else { return nil }
        return png
    }
}
